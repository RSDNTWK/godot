#!/usr/bin/env python3
"""Compile FFmpeg 9.0.2's patched ARM32 kernels with the Android NDK assembler.

Run against an ARM/NEON configuration generated by FFmpeg configure with the
NDK compiler (HAVE_AS_DN_DIRECTIVE=0). No GNU assembler is required. The pinned
syntax-only hashes match the original GNU-assembled kernels. --safety-patch
checks the separately reviewed alignment-safe store instructions instead.
"""

import argparse
import hashlib
from pathlib import Path
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', required=True, type=Path)
    parser.add_argument('--config', required=True, type=Path)
    parser.add_argument('--cc', required=True, type=Path)
    parser.add_argument('--objcopy', required=True, type=Path)
    parser.add_argument('--safety-patch', action='store_true', help='Also applied arm32-unscaled-conversion-safety.patch')
    args = parser.parse_args()
    config = (args.config / 'config.h').read_text()
    for expected in ['#define ARCH_ARM 1', '#define HAVE_NEON 1', '#define HAVE_AS_DN_DIRECTIVE 0']:
        assert expected in config, 'Use an NDK-generated ARM/NEON config: ' + expected
    hashes = {
        16: '02ba8a7e61111d0457c4094911ed24df866d64e08578b61f6305b8b67caaa03b',
        32: '0eba4ae179870952004359bcb4a2460e83350e30c8c8ba8c24c1a7cdbc43d8a2',
    }
    if args.safety_patch:
        hashes = {
            16: '5208668ce9734ceda71928a163b59f923544dcad4bd90b6c6314c8b85ea18396',
            32: '8eea5fe922cffd4b1acb03998609b43055697c571317fc87cfcfdf9cb2132707',
        }
    with tempfile.TemporaryDirectory(prefix='ffmpeg-arm32-neon-syntax-') as directory:
        for precision, expected in hashes.items():
            assembly = args.source / f'libswscale/arm/rgb2yuv_neon_{precision}.S'
            obj = Path(directory) / f'kernel-{precision}.o'
            binary = obj.with_suffix('.text')
            subprocess.run([str(args.cc), '-march=armv7-a', '-mfloat-abi=softfp', '-mfpu=neon', '-fPIC', '-marm', '-I' + str(args.config), '-I' + str(args.source), '-c', str(assembly), '-o', str(obj)], check=True)
            subprocess.run([str(args.objcopy), '--dump-section=.text=' + str(binary), str(obj)], check=True)
            assert hashlib.sha256(binary.read_bytes()).hexdigest() == expected, 'Kernel instruction bytes changed: ' + str(precision)
            description = 'reviewed alignment-safe kernel' if args.safety_patch else 'upstream GNU assembly'
            print(f'PASS: {precision}-bit kernel assembles without .dn; machine code matches {description}')


if __name__ == '__main__':
    main()
